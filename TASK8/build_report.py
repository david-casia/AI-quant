def print_pdf_via_browser(html_path, pdf_path):
    import subprocess
    import shutil as _shutil
    candidates = [
        r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
        r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    ]
    browser = None
    for c in candidates:
        if os.path.exists(c):
            browser = c
            break
    if browser is None:
        browser = _shutil.which("msedge") or _shutil.which("chrome")
    if browser is None:
        raise RuntimeError("未找到 Edge 或 Chrome 浏览器")

    abs_html = os.path.abspath(html_path).replace(os.sep, '/')
    abs_pdf = os.path.abspath(pdf_path)
    cmd = [
        browser, "--headless=new", "--disable-gpu", "--no-sandbox",
        "--no-pdf-header-footer",
        f"--print-to-pdf={abs_pdf}",
        f"file:///{abs_html}",
    ]
    print(f"使用浏览器: {browser}")
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    if not os.path.exists(abs_pdf):
        raise RuntimeError(f"PDF生成失败: {result.stderr or result.stdout}")


