    parts.append(P(f'量化交易的发展可划分为三个阶段。第一阶段为{B("技术指标自动化阶段")}（1980年代至1990年代），以移动平均线、相对强弱指标等经典技术指标为基础，通过计算机程序自动识别交易信号，代表人物如约翰·墨菲与约翰·布林格。第二阶段为{B("统计套利阶段")}（1990年代至2000年代），以配对交易、均值回归、统计因子模型为代表，引入严格的统计检验和组合优化方法，量化对冲基金如文艺复兴科技、Two Sigma在此期间崛起。第三阶段为{B("人工智能量化阶段")}（2010年代至今），深度学习、强化学习等技术被引入交易策略，机器学习模型在多因子合成与非线性特征挖掘方面展现出超越传统统计方法的能力。本项目涵盖了前两阶段的代表性方法以及第三阶段的入门级实践。'))

    parts.append(H3('1.2 量化交易的核心价值与适用边界'))
    parts.append(P(f'量化交易的核心价值体现在四个维度。{B("客观性")}是其首要优势——预设规则确保了交易执行的一致性，避免了恐惧、贪婪、过度自信等情绪偏差对决策的干扰，这在行为金融学研究中已被反复证实为导致投资者损失的关键因素。{B("效率性")}体现在计算机可在毫秒级别处理海量市场数据并生成决策，远超人工分析的速度与覆盖范围。{B("可验证性")}是科学方法在投资领域的应用——所有策略都可在历史数据上回测，使用年化收益率、夏普比率、最大回撤等量化指标客观评估表现，避免"事后诸葛"式主观判断。{B("可扩展性")}指一套成熟策略可同时监控数百乃至数千只标的，实现低成本分散化。'))
